const grid=document.getElementById('blogGrid');
const reader=document.getElementById('blogReader');
const searchInput=document.getElementById('blogSearch');
const tagFilter=document.getElementById('blogTagFilter');

const blogEscapeHTML = (value='') => String(value)
  .replaceAll('&','&amp;')
  .replaceAll('<','&lt;')
  .replaceAll('>','&gt;')
  .replaceAll('"','&quot;')
  .replaceAll("'",'&#039;');

function renderBlog(){
  if(!grid) return;
  const q=(searchInput?.value||'').trim().toLowerCase();
  const tag=tagFilter?.value||'ALL';
  const filtered=BLOG_DATA.filter(post=>{
    const matchesTag=tag==='ALL'||post.tag===tag;
    const hay=`${post.title} ${post.excerpt} ${post.tag}`.toLowerCase();
    return matchesTag && (!q || hay.includes(q));
  });

  grid.innerHTML=filtered.length ? filtered.map((post,index)=>`
    <article class="blog-card ${index===0 && !q && tag==='ALL' ? 'blog-card-featured' : ''}">
      <div class="blog-card-meta"><span class="blog-tag">${blogEscapeHTML(post.tag)}</span><span>${blogEscapeHTML(post.readTime)}</span></div>
      <h3>${blogEscapeHTML(post.title)}</h3>
      <p>${blogEscapeHTML(post.excerpt)}</p>
      <button class="text-link blog-read-button" type="button" data-blog-id="${blogEscapeHTML(post.id)}">Read guide <span>→</span></button>
    </article>`).join('') : `
    <div class="tools-empty-state blog-empty" style="grid-column:1/-1">
      <div class="empty-state-icon">⌕</div>
      <h3>No guide found</h3>
      <p>Try a different phrase or choose another category.</p>
    </div>`;
}

function openBlog(id){
  if(!reader) return;
  const post=BLOG_DATA.find(item=>item.id===id);
  if(!post) return;
  const related=post.related.map(id=>window.toolVault?.TOOL_DATA?.find(t=>t.id===id)).filter(Boolean);
  reader.innerHTML=`
    <div class="blog-reader-backdrop" data-close-reader></div>
    <article class="blog-reader-panel" role="dialog" aria-modal="true" aria-labelledby="blogReaderTitle">
      <div class="blog-reader-head">
        <div><span class="blog-tag">${blogEscapeHTML(post.tag)}</span><span class="blog-reader-time">${blogEscapeHTML(post.readTime)}</span></div>
        <button class="blog-reader-close" type="button" aria-label="Close guide" data-close-reader>&times;</button>
      </div>
      <h2 id="blogReaderTitle">${blogEscapeHTML(post.title)}</h2>
      <p class="blog-reader-lead">${blogEscapeHTML(post.excerpt)}</p>
      <div class="blog-reader-content">${post.sections.map(([heading,text],index)=>`<section><span class="blog-step">${String(index+1).padStart(2,'0')}</span><div><h3>${blogEscapeHTML(heading)}</h3><p>${blogEscapeHTML(text)}</p></div></section>`).join('')}</div>
      ${related.length ? `<div class="blog-related"><span class="eyebrow">RELATED TOOLS</span><div class="blog-related-links">${related.map(tool=>`<a class="related-tool-card" href="tool.html?id=${encodeURIComponent(tool.id)}">${window.toolVault.logoMarkup(tool)}<div><strong>${blogEscapeHTML(tool.name)}</strong><small>${blogEscapeHTML(tool.categoryLabel)}</small></div><span>→</span></a>`).join('')}</div></div>` : ''}
      <div class="blog-reader-footer"><p>ToolVault may earn a commission from qualifying affiliate links. Product details and commercial terms should be confirmed on the provider’s current site.</p><a class="btn btn-primary" href="tools.html">Explore Tools <span>→</span></a></div>
    </article>`;
  reader.hidden=false;
  reader.classList.add('open');
  document.body.classList.add('modal-open');
}

function closeBlog(){
  if(!reader) return;
  reader.classList.remove('open');
  document.body.classList.remove('modal-open');
  setTimeout(()=>{ if(!reader.classList.contains('open')) reader.hidden=true; },180);
}

if(grid){
  grid.addEventListener('click',event=>{
    const button=event.target.closest('[data-blog-id]');
    if(button) openBlog(button.dataset.blogId);
  });
  renderBlog();
}
searchInput?.addEventListener('input',renderBlog);
tagFilter?.addEventListener('change',renderBlog);
reader?.addEventListener('click',event=>{ if(event.target.closest('[data-close-reader]')) closeBlog(); });
document.addEventListener('keydown',event=>{ if(event.key==='Escape') closeBlog(); });
