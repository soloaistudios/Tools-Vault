const escapeHTML = (value='') => String(value)
  .replaceAll('&','&amp;')
  .replaceAll('<','&lt;')
  .replaceAll('>','&gt;')
  .replaceAll('"','&quot;')
  .replaceAll("'",'&#039;');

function logoClass(id){
  return `${id}-logo`;
}

function logoMarkup(tool, extraClass=''){
  const id = escapeHTML(tool.id);
  const name = escapeHTML(tool.name);
  const initial = escapeHTML(tool.name.charAt(0));

  return `<div class="tool-logo ${escapeHTML(extraClass)} ${escapeHTML(logoClass(tool.id))}" data-logo-id="${id}">` +
    `<span class="logo-placeholder" aria-hidden="true">${initial}</span>` +
    `<img class="tool-logo-image" src="assets/logos/${encodeURIComponent(tool.id)}.png" alt="${name} logo" loading="lazy" decoding="async" onload="this.previousElementSibling.hidden=true" onerror="this.hidden=true">` +
    `</div>`;
}

function toolCard(tool){
  return `<article class="tool-card" data-id="${escapeHTML(tool.id)}" data-category="${escapeHTML(tool.category)}" data-type="${escapeHTML(tool.type)}" data-featured="${Boolean(tool.featured)}" data-popular="${Boolean(tool.popular)}" data-name="${escapeHTML(tool.name)}">
    <div class="tool-card-top">
      <span class="tool-category-badge">${escapeHTML(tool.categoryLabel)}</span>
      ${logoMarkup(tool)}
    </div>
    <div class="tool-card-body">
      <h3>${escapeHTML(tool.name)}</h3>
      <p>${escapeHTML(tool.description)}</p>
      <ul class="tool-feature-list">${tool.features.slice(0,3).map(f=>`<li><span>✓</span>${escapeHTML(f)}</li>`).join('')}</ul>
    </div>
    <div class="tool-card-footer">
      <div class="tool-card-actions">
        <a class="btn btn-primary btn-small" href="tool.html?id=${encodeURIComponent(tool.id)}">View Tool <span>→</span></a>
        <button type="button" class="btn btn-outline btn-small compare-button" data-compare-id="${escapeHTML(tool.id)}" aria-pressed="false">＋ Compare</button>
      </div>
    </div>
  </article>`;
}

function renderFeatured(){
  const target = document.getElementById('featuredTools');
  if (!target) return;

  target.innerHTML = TOOL_DATA
    .filter(t => t.featured)
    .slice(0,5)
    .map(toolCard)
    .join('');
}

function renderAllTools(list=TOOL_DATA){
  const target = document.getElementById('toolsGrid');
  if (!target) return;

  target.innerHTML = list
    .map(toolCard)
    .join('');

  const count = document.getElementById('resultsCount');

  if (count) {
    count.textContent = list.length;
  }
}

